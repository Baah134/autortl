"""Testbench autogeneration with two comparison modes (Pothole 2 resolution).

fixed_latency : golden outputs pass through an N-deep shift register before
                comparison (the "15-line core").
scoreboard    : queue-based; each accepted input pushes an expected output,
                each DUT output-valid pops and compares. Latency-agnostic.

Reset/X discipline (defence #8): reset applied per spec, settle margin
observed, comparison window opens only afterwards.
"""
from __future__ import annotations
import json
import random
from pathlib import Path
from .spec import ModuleSpec
from .golden import GoldenModel


def gen_stimulus(spec: ModuleSpec, n_random: int = 100,
                 seed: int = 1234) -> list[dict]:
    """Deterministic randomized + corner stimulus for data inputs."""
    rng = random.Random(seed)
    data_ins = [p for p in spec.ports
                if p.direction == "input"
                and p.name not in ("clk", spec.reset.signal)
                and p.protocol == "none"]
    stim: list[dict] = []
    # corners
    for val_fn in (lambda w: 0, lambda w: (1 << w) - 1, lambda w: 1 << (w - 1) if w > 1 else 1):
        stim.append({p.name: val_fn(p.width) for p in data_ins})
    # random
    for _ in range(n_random):
        stim.append({p.name: rng.randrange(0, 1 << p.width) for p in data_ins})
    return stim


def expected_outputs(spec: ModuleSpec, golden: GoldenModel,
                     stimulus: list[dict]) -> list[dict]:
    return golden.run(stimulus)


def _fmt(v: int, width: int) -> str:
    return f"{width}'d{v}"


def generate_fixed_latency_tb(spec: ModuleSpec, stimulus: list[dict],
                              expected: list[dict]) -> str:
    """Self-checking tb: drives stimulus one per cycle, compares outputs
    delayed by spec.latency cycles against the golden expectations."""
    r = spec.reset
    data_ins = [p for p in spec.ports if p.direction == "input"
                and p.name not in ("clk", r.signal) and p.protocol == "none"]
    data_outs = [p for p in spec.ports if p.direction == "output"
                 and p.protocol == "none"]
    n = len(stimulus)
    lat = spec.latency

    decl_ins = "\n".join(f"    reg [{p.width-1}:0] {p.name};" if p.width > 1
                         else f"    reg {p.name};" for p in data_ins)
    decl_outs = "\n".join(f"    wire [{p.width-1}:0] {p.name};" if p.width > 1
                          else f"    wire {p.name};" for p in data_outs)
    conns = ", ".join(f".{p.name}({p.name})" for p in spec.ports
                      if p.name not in ("clk", r.signal))
    stim_arrays = []
    for p in data_ins:
        vals = ", ".join(_fmt(s.get(p.name, 0), p.width) for s in stimulus)
        stim_arrays.append(
            f"    reg [{p.width-1}:0] stim_{p.name} [0:{n-1}];\n"
            f"    initial begin\n"
            + "\n".join(f"        stim_{p.name}[{i}] = "
                        f"{_fmt(stimulus[i].get(p.name,0), p.width)};"
                        for i in range(n))
            + "\n    end")
    exp_arrays = []
    for p in data_outs:
        exp_arrays.append(
            f"    reg [{p.width-1}:0] exp_{p.name} [0:{n-1}];\n"
            f"    initial begin\n"
            + "\n".join(f"        exp_{p.name}[{i}] = "
                        f"{_fmt(expected[i].get(p.name,0), p.width)};"
                        for i in range(n))
            + "\n    end")
    checks = "\n".join(
        f"""            if ({p.name} !== exp_{p.name}[chk_idx]) begin
                $display("FAIL index=%0d signal={p.name} expected=%0d got=%0d",
                         chk_idx, exp_{p.name}[chk_idx], {p.name});
                errors = errors + 1;
            end""" for p in data_outs)
    rst_assert = "1'b1" if r.active_high else "1'b0"
    rst_release = "1'b0" if r.active_high else "1'b1"

    return f"""// AUTOGENERATED self-checking testbench ({spec.name}, fixed_latency={lat})
`timescale 1ns/1ps
module {spec.name}_tb;
    reg clk;
    reg {r.signal};
{decl_ins}
{decl_outs}
    integer drv_idx, chk_idx, errors;

{chr(10).join(stim_arrays)}
{chr(10).join(exp_arrays)}

    {spec.name} dut (.clk(clk), .{r.signal}({r.signal}), {conns});

    always #5 clk = ~clk;

    initial begin
        clk = 0; errors = 0; drv_idx = 0; chk_idx = 0;
        {r.signal} = {rst_assert};
        repeat ({r.duration_cycles}) @(posedge clk);
        {r.signal} = {rst_release};
        repeat (2) @(posedge clk);        // settle margin (X-propagation discipline)

        // drive + check with a latency offset of {lat}
        while (chk_idx < {n}) begin
            @(posedge clk);
            if (drv_idx < {n}) begin
{chr(10).join(f'                {p.name} <= stim_{p.name}[drv_idx];' for p in data_ins)}
                drv_idx = drv_idx + 1;
            end
            #1;
            if (drv_idx > {lat} && chk_idx < drv_idx - {lat}) begin
{checks}
                chk_idx = chk_idx + 1;
            end
        end
        if (errors == 0) $display("TEST PASSED");
        else $display("TEST FAILED: %0d errors", errors);
        $finish;
    end
endmodule
"""


def generate_scoreboard_tb(spec: ModuleSpec, stimulus: list[dict],
                           expected: list[dict]) -> str:
    """Queue-based scoreboard for valid/ready streaming modules.
    Latency-agnostic: compares transaction order + values only."""
    r = spec.reset
    vr_in = [p for p in spec.ports if p.protocol == "valid_ready" and p.direction == "input"]
    vr_out = [p for p in spec.ports if p.protocol == "valid_ready" and p.direction == "output"]
    in_valid = next((p.name for p in vr_in if p.name.endswith("valid")), "in_valid")
    in_ready = next((p.name for p in vr_out if p.name.endswith("ready")), "in_ready")
    out_valid = next((p.name for p in vr_out if p.name.endswith("valid")), "out_valid")
    out_ready = next((p.name for p in vr_in if p.name.endswith("ready")), "out_ready")
    data_ins = [p for p in spec.ports if p.direction == "input" and p.protocol == "none"
                and p.name not in ("clk", r.signal)]
    data_outs = [p for p in spec.ports if p.direction == "output" and p.protocol == "none"]
    n = len(stimulus)
    dout = data_outs[0] if data_outs else None
    din = data_ins[0] if data_ins else None
    rst_assert = "1'b1" if r.active_high else "1'b0"
    rst_release = "1'b0" if r.active_high else "1'b1"
    exp_vals = ", ".join(_fmt(expected[i].get(dout.name, 0), dout.width) for i in range(n)) if dout else ""
    stim_vals = ", ".join(_fmt(stimulus[i].get(din.name, 0), din.width) for i in range(n)) if din else ""

    return f"""// AUTOGENERATED scoreboard testbench ({spec.name}, valid/ready)
`timescale 1ns/1ps
module {spec.name}_tb;
    reg clk; reg {r.signal};
    reg {in_valid}; wire {in_ready};
    wire {out_valid}; reg {out_ready};
    reg [{din.width-1}:0] {din.name};
    wire [{dout.width-1}:0] {dout.name};
    integer push_idx, pop_idx, errors, backoff;

    reg [{din.width-1}:0] stim [0:{n-1}];
    reg [{dout.width-1}:0] expq [0:{n-1}];
    initial begin
{chr(10).join(f'        stim[{i}] = {_fmt(stimulus[i].get(din.name,0), din.width)};' for i in range(n))}
{chr(10).join(f'        expq[{i}] = {_fmt(expected[i].get(dout.name,0), dout.width)};' for i in range(n))}
    end

    {spec.name} dut (.clk(clk), .{r.signal}({r.signal}),
        .{in_valid}({in_valid}), .{in_ready}({in_ready}),
        .{out_valid}({out_valid}), .{out_ready}({out_ready}),
        .{din.name}({din.name}), .{dout.name}({dout.name}));

    always #5 clk = ~clk;

    initial begin
        clk = 0; errors = 0; push_idx = 0; pop_idx = 0; backoff = 0;
        {in_valid} = 0; {out_ready} = 1; {din.name} = 0;
        {r.signal} = {rst_assert};
        repeat ({r.duration_cycles}) @(posedge clk);
        {r.signal} = {rst_release};
        repeat (2) @(posedge clk);

        while (pop_idx < {n}) begin
            @(posedge clk); #1;
            // drive side: valid/ready handshake, with occasional backpressure test
            if (push_idx < {n}) begin
                {in_valid} <= 1;
                {din.name} <= stim[push_idx];
                if ({in_valid} && {in_ready}) push_idx = push_idx + 1;
            end else {in_valid} <= 0;
            // periodic ready deassertion exercises backpressure
            backoff = backoff + 1;
            {out_ready} <= (backoff % 7 != 0);
            // pop side: scoreboard compare on every accepted output beat
            if ({out_valid} && {out_ready}) begin
                if ({dout.name} !== expq[pop_idx]) begin
                    $display("FAIL index=%0d expected=%0d got=%0d",
                             pop_idx, expq[pop_idx], {dout.name});
                    errors = errors + 1;
                end
                pop_idx = pop_idx + 1;
            end
        end
        if (errors == 0) $display("TEST PASSED");
        else $display("TEST FAILED: %0d errors", errors);
        $finish;
    end
endmodule
""" if din and dout else "// scoreboard tb requires one data in and one data out port\n"


def generate(spec: ModuleSpec, golden: GoldenModel, out_dir: Path,
             n_random: int = 100, seed: int = 1234) -> Path:
    stim = gen_stimulus(spec, n_random=n_random, seed=seed)
    exp = expected_outputs(spec, golden, stim)
    if spec.compare_mode == "scoreboard":
        text = generate_scoreboard_tb(spec, stim, exp)
    elif spec.compare_mode == "fixed_latency":
        text = generate_fixed_latency_tb(spec, stim, exp)
    else:
        raise NotImplementedError(
            f"compare_mode '{spec.compare_mode}' is stubbed in v4.0 — "
            f"use fixed_latency or scoreboard")
    out_dir.mkdir(parents=True, exist_ok=True)
    tb = out_dir / f"{spec.name}_tb.v"
    tb.write_text(text)
    (out_dir / "stimulus.json").write_text(json.dumps(
        {"stimulus": stim, "expected": exp}, indent=1))
    return tb
